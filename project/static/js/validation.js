document.addEventListener('DOMContentLoaded', function () {
    // ============================================================
    // 2. ВАЛИДАЦИЯ ФОРМЫ РЕГИСТРАЦИИ
    // ============================================================
    // Ищем форму регистрации по id="register-form".
    // На странице входа такой формы нет — вернётся null.
    var regForm = document.getElementById('register-form');

    // Проверяем, что форма существует (мы на странице регистрации).
    // Если формы нет — блок не выполнится, ошибки не будет.
    if (regForm) {

        // Слушаем событие 'submit' — момент, когда пользователь
        // нажал кнопку «Создать пользователя» или Enter.
        regForm.addEventListener('submit', function (e) {

            // Массив для сообщений об ошибках.
            // Если он останется пустым — данные корректны.
            var errors = [];

            // ---------- Получаем значения из полей ----------
            // .value — то, что ввёл пользователь.
            // .trim() — убираем пробелы по краям ("  test  " → "test").

            var login    = document.getElementById('login').value.trim();
            var password = document.getElementById('password').value;       // без trim — пробел может быть частью пароля
            var fullname = document.getElementById('fullname').value.trim();
            var phone    = document.getElementById('phone').value.trim();
            var email    = document.getElementById('email').value.trim();

            // ---------- Проверка логина ----------
            // Требование: латиница + цифры, минимум 6 символов.
            // Регулярка: /^[A-Za-z0-9]{6,}$/
            //   ^ — начало строки
            //   [A-Za-z0-9] — любая латинская буква или цифра
            //   {6,} — минимум 6 таких символов
            //   $ — конец строки
            if (!/^[A-Za-z0-9]{6,}$/.test(login)) {
                errors.push('Логин: только латиница и цифры, минимум 6 символов');
            }

            // ---------- Проверка пароля ----------
            // Требование: минимум 8 символов.
            if (password.length < 8) {
                errors.push('Пароль: минимум 8 символов');
            }

            // ---------- Проверка ФИО ----------
            // Требование: только кириллица и пробелы.
            // [А-Яа-яЁё] — русские буквы (заглавные и строчные, включая Ё)
            // \s — пробельный символ
            if (!/^[А-Яа-яЁё\s]+$/.test(fullname)) {
                errors.push('ФИО: только кириллица и пробелы');
            }

            // ---------- Проверка телефона ----------
            // Требование: формат 8(XXX)XXX-XX-XX.
            // 8 — буквально цифра 8
            // \( — экранированная открывающая скобка
            // \d{3} — три цифры
            // \) — закрывающая скобка
            // \d{3} — три цифры
            // - — дефис
            // \d{2} — две цифры
            if (!/^8\(\d{3}\)\d{3}-\d{2}-\d{2}$/.test(phone)) {
                errors.push('Телефон: формат 8(XXX)XXX-XX-XX');
            }

            // ---------- Проверка email ----------
            // Требование: простой формат user@domain.zone.
            // [^@\s]+ — один или больше символов, кроме @ и пробела
            // @ — буквально собака
            // \. — экранированная точка
            if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email)) {
                errors.push('Email: некорректный формат');
            }

            // ---------- Если есть ошибки — показываем и блокируем отправку ----------
            if (errors.length > 0) {
                // preventDefault() отменяет стандартное действие браузера:
                // форма НЕ отправится на сервер, пока пользователь не исправит ошибки.
                e.preventDefault();

                // Выводим блок ошибок над формой.
                // 'reg-errors' — это значение атрибута data-testid для блока ошибок.
                showErrors(regForm, errors, 'reg-errors');
            }
            // Если ошибок нет — форма отправится автоматически (POST на /register).
        });
    }
    // ============================================================
    // 3. ВАЛИДАЦИЯ ФОРМЫ ВХОДА
    // ============================================================

    // Ищем форму входа по id="login-form".
    var loginForm = document.getElementById('login-form');

    if (loginForm) {

        loginForm.addEventListener('submit', function (e) {

            var errors = [];

            // Получаем значения полей.
            var login    = document.getElementById('login').value.trim();
            var password = document.getElementById('password').value;

            // ---------- Простая проверка: поля не пустые ----------
            // При входе не нужно проверять формат — пользователь уже
            // зарегистрирован, значит данные были валидны при регистрации.
            // Достаточно убедиться, что он вообще что-то ввёл.

            if (!login) {
                errors.push('Введите логин');
            }
            if (!password) {
                errors.push('Введите пароль');
            }

            // ---------- Если есть ошибки — блокируем отправку ----------
            if (errors.length > 0) {
                e.preventDefault();
                showErrors(loginForm, errors, 'login-errors');
            }
        });
    }
    // ============================================================
    // 4. ФУНКЦИЯ ПОКАЗА ОШИБОК
    // ============================================================
    // Принимает:
    //   form        — HTML-элемент формы, ПЕРЕД которой вставим блок
    //   errors      — массив строк с сообщениями
    //   containerId — значение для data-testid (reg-errors или login-errors)
    function showErrors(form, errors, containerId) {

        // ---------- Удаляем старый блок ошибок, если он есть ----------
        // Иначе при повторном нажатии кнопки блоки будут дублироваться.
        var old = document.querySelector('[data-testid="' + containerId + '"]');
        if (old) {
            old.remove();
        }

        // ---------- Создаём новый <div> ----------
        var div = document.createElement('div');

        // CSS-класс для оформления (красный фон и т.д.).
        div.className = 'errors';

        // Атрибут data-testid — по нему автотест находит блок ошибок.
        div.setAttribute('data-testid', containerId);

        // ---------- Формируем HTML внутри ----------
        // errors.map(...) — превращает каждую строку в '<li>строка</li>'.
        // .join('')      — склеивает массив в одну строку без разделителей.
        // '<ul>...</ul>' — оборачиваем в ненумерованный список.
        div.innerHTML = '<ul>' + errors.map(function (err) {
            return '<li>' + err + '</li>';
        }).join('') + '</ul>';

        // ---------- Вставляем блок ПЕРЕД формой ----------
        // form.parentNode — родительский элемент формы (например, <main>).
        // insertBefore(div, form) — вставляет div перед form.
        form.parentNode.insertBefore(div, form);
    }

});